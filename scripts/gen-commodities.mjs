// Generate the commodity-expansion artifacts from scripts/commodities.data.mjs:
//   1. scripts/out/proposed_commodities.csv  — REVIEW this first (human sign-off)
//   2. supabase/migrations/<UTCstamp>_expand_commodities.sql — paste after review
//
//   node scripts/gen-commodities.mjs
//
// The migration is ON CONFLICT (slug) DO NOTHING, so it is safe to re-run and
// never clobbers a curated row.

import { writeFileSync, mkdirSync } from "node:fs";
import { COMMODITIES } from "./commodities.data.mjs";

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const jsonb = (obj) => `${q(JSON.stringify(obj))}::jsonb`;

function csvCell(v) {
  const s = v == null ? "" : String(v);
  return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

function main() {
  mkdirSync(new URL("./out/", import.meta.url), { recursive: true });

  // 1. Reviewable CSV
  const header = [
    "slug", "display_name", "category", "heavy_metal_tier", "pesticide_tier",
    "organic_pesticide_mitigation", "notes", "sources",
  ];
  const csv = [header.join(",")];
  for (const c of COMMODITIES) {
    csv.push(
      [
        c.slug, c.display_name, c.category, c.heavy_metal_tier, c.pesticide_tier,
        c.organic_pesticide_mitigation, c.notes ?? "",
        c.sources.map((s) => s.name).join(" | "),
      ].map(csvCell).join(","),
    );
  }
  const csvUrl = new URL("./out/proposed_commodities.csv", import.meta.url);
  writeFileSync(csvUrl, csv.join("\n") + "\n");

  // 2. Migration
  const lines = [];
  lines.push("-- Commodity expansion (HANDOFF §9).");
  lines.push("-- Generated by scripts/gen-commodities.mjs from commodities.data.mjs.");
  lines.push("-- Tiers sourced (EWG 2024 for pesticide; FDA/CR/HBBF for heavy metal).");
  lines.push("-- Paste into the Supabase SQL Editor. Safe to re-run (ON CONFLICT DO NOTHING).");
  lines.push("");
  lines.push(
    "insert into commodities\n" +
      "  (slug, display_name, category, heavy_metal_tier, pesticide_tier,\n" +
      "   organic_pesticide_mitigation, notes, sources)\n" +
      "values",
  );
  const values = COMMODITIES.map((c) => {
    const notes = c.notes == null ? "null" : q(c.notes);
    return (
      `  (${q(c.slug)}, ${q(c.display_name)}, ${q(c.category)}, ` +
      `${c.heavy_metal_tier}, ${c.pesticide_tier}, ${c.organic_pesticide_mitigation}, ` +
      `${notes}, ${jsonb(c.sources)})`
    );
  });
  lines.push(values.join(",\n"));
  lines.push("on conflict (slug) do nothing;");

  const stamp = new Date().toISOString().replace(/[-:T]/g, "").slice(0, 14);
  const sqlUrl = new URL(
    `../supabase/migrations/${stamp}_expand_commodities.sql`,
    import.meta.url,
  );
  writeFileSync(sqlUrl, lines.join("\n") + "\n");

  console.log(`commodities: ${COMMODITIES.length}`);
  console.log(`review CSV:  ${csvUrl.pathname.replace(/%20/g, " ")}`);
  console.log(`migration:   ${sqlUrl.pathname.replace(/%20/g, " ")}`);
}

main();
