// Turn the REVIEWED scripts/out/proposed_plu.csv into a PLU seed migration.
//
//   node scripts/plu-csv-to-sql.mjs [--in path/to.csv]
//
// For every conventional 4-digit code it also emits the organic twin (the same
// code prefixed with 9, per the IFPS convention) — is_organic is a generated
// column, so the twin scores as organic automatically. This mirrors how the
// init migration seeds banana (4011 + 94011) and roughly doubles coverage.
//
// commodity_id is resolved by slug via a JOIN, so a code whose commodity does
// not exist yet is simply skipped, never an error. Run the commodity-expansion
// migration first. Safe to re-run (ON CONFLICT (code) DO NOTHING).

import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { COMMODITIES } from "./commodities.data.mjs";

const EXISTING = [
  "spinach", "kale", "carrot", "sweet_potato", "potato", "strawberry",
  "blueberry", "green_bean", "bell_pepper", "peach", "pea", "broccoli",
  "winter_squash", "banana",
];
const ALL_SLUGS = new Set([...EXISTING, ...COMMODITIES.map((c) => c.slug)]);

function arg(name, fallback) {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 && process.argv[i + 1] ? process.argv[i + 1] : fallback;
}

function parseCsv(text) {
  const rows = [];
  for (const line of text.trim().split("\n")) {
    const cells = [];
    let cur = "", q = false;
    for (const c of line) {
      if (c === '"') q = !q;
      else if (c === "," && !q) { cells.push(cur); cur = ""; }
      else cur += c;
    }
    cells.push(cur);
    rows.push(cells);
  }
  const header = rows.shift();
  return rows.map((r) => Object.fromEntries(header.map((h, i) => [h, (r[i] ?? "").trim()])));
}

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

function main() {
  const inUrl = arg("in")
    ? new URL(arg("in"), `file://${process.cwd()}/`)
    : new URL("./out/proposed_plu.csv", import.meta.url);
  const rows = parseCsv(readFileSync(inUrl, "utf8"));

  const values = [];
  const skipped = [];
  const seen = new Set();
  for (const r of rows) {
    const code = (r.code || "").trim();
    const name = (r.display_name || "").trim();
    const slug = (r.commodity_slug || "").trim();
    if (!/^[0-9]{4}$/.test(code) || !name || !ALL_SLUGS.has(slug)) {
      skipped.push(`${code || "?"} ${name || "?"} (bad code/name/slug)`);
      continue;
    }
    for (const c of [code, `9${code}`]) {
      if (seen.has(c)) continue;
      seen.add(c);
      values.push(`  (${q(c)}, ${q(slug)}, ${q(name)})`);
    }
  }

  const lines = [];
  lines.push("-- PLU seed (HANDOFF §9, part 2).");
  lines.push("-- Generated by scripts/plu-csv-to-sql.mjs from a reviewed IFPS mapping.");
  lines.push("-- Run the commodity-expansion migration FIRST. Safe to re-run.");
  lines.push("-- Each conventional code also gets its organic 9-prefixed twin.");
  lines.push("");
  lines.push("insert into plu_codes (code, commodity_id, display_name)");
  lines.push("select v.code, c.id, v.display_name");
  lines.push("from (values");
  lines.push(values.join(",\n"));
  lines.push(") as v(code, slug, display_name)");
  lines.push("join commodities c on c.slug = v.slug");
  lines.push("on conflict (code) do nothing;");

  const stamp = new Date().toISOString().replace(/[-:T]/g, "").slice(0, 14);
  const outUrl = new URL(`../supabase/migrations/${stamp}_seed_plu_codes.sql`, import.meta.url);
  writeFileSync(outUrl, lines.join("\n") + "\n");

  console.log(`read:      ${inUrl.pathname.replace(/%20/g, " ")}`);
  console.log(`codes:     ${values.length} (conventional + organic twins)`);
  console.log(`skipped:   ${skipped.length}`);
  skipped.slice(0, 8).forEach((s) => console.log(`  - ${s}`));
  console.log(`migration: ${outUrl.pathname.replace(/%20/g, " ")}`);
}

main();
